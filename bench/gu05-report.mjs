#!/usr/bin/env node
// GU-05 report: hono after adopting Repo Archaeology's library session and import resolver, next to the
// GU-29 numbers; the research switch against Stage 0b, with every per-PR delta classified; Gate A′.
//
// Zero dependencies; plain Node >= 22. Deterministic: same inputs, same output.
//
//   node bench/gu05-report.mjs --default <gu05 default bench.json> --legacy <gu05 legacy bench.json> \
//     --stage0b docs/benchmark/data/honojs__hono/stage0b/default/bench.json \
//     --gu29 docs/benchmark/data/honojs__hono/gu29/results.json \
//     --gate <gu05 gate-a-prime.json> --write-results docs/benchmark/data/honojs__hono/gu05/results.json
//   node bench/gu05-report.mjs --results docs/benchmark/data/honojs__hono/gu05/results.json --update docs/benchmark/STAGE0.md
import { readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { replaceGeneratedBlock, summarizeRun } from './stage0-report.mjs';
import { evaluateGate, gateSummary, runShape } from './gu29-report.mjs';

export const MARK_GU05_START = '<!-- gu05:results:start (generated by bench/gu05-report.mjs; do not edit by hand) -->';
export const MARK_GU05_END = '<!-- gu05:results:end -->';

const prLabel = (p) => (p.prNumber !== null ? `#${p.prNumber}` : p.id);

/**
 * Why a PR record differs between Stage 0b's default run and the GU-05 legacy run. Classes:
 *  - `dependents`: broken-import / wide-surface items differ (the import resolver found other importers);
 *  - `interval`: a companion question's interval low bound differs (RA's outward-rounded interval);
 *  - `questions`: other checklist differences (an item crossed a gate, or the 4-item cap moved);
 *  - `salience`, `outcomes`, `baselines`: knock-on effects of the above.
 */
export function classifyDeltas(stage0b, legacy) {
  const byId = new Map(legacy.prs.map((p) => [p.id, p]));
  const rows = [];
  let maxIntervalDelta = 0;
  for (const a of stage0b.prs) {
    const b = byId.get(a.id);
    if (!b || JSON.stringify(a) === JSON.stringify(b)) continue;
    const qa = a.policies.production.questions;
    const qb = b.policies.production.questions;
    const ids = (qs, kinds) => qs.filter((q) => kinds.includes(q.kind)).map((q) => q.id).sort().join('|');
    const reasons = new Set();
    if (ids(qa, ['broken-import', 'wide-surface']) !== ids(qb, ['broken-import', 'wide-surface'])) reasons.add('dependents');
    const low = new Map(qb.map((q) => [q.id, q.intervalLow]));
    for (const q of qa) {
      if (q.kind !== 'forgotten-companion' || !low.has(q.id) || low.get(q.id) === q.intervalLow) continue;
      reasons.add('interval');
      if (typeof q.intervalLow === 'number' && typeof low.get(q.id) === 'number') {
        maxIntervalDelta = Math.max(maxIntervalDelta, Math.abs(low.get(q.id) - q.intervalLow));
      }
    }
    const other = (qs) => qs.filter((q) => !['broken-import', 'wide-surface'].includes(q.kind)).map((q) => q.id).sort().join('|');
    if (other(qa) !== other(qb)) reasons.add('questions');
    if (a.policies.production.salience !== b.policies.production.salience) reasons.add('salience');
    const strip = (qs) => JSON.stringify(qs.map(({ intervalLow, ...rest }) => rest));
    if (!reasons.size && strip(qa) !== strip(qb)) reasons.add('outcomes');
    if (JSON.stringify(a.policies.production.baselines) !== JSON.stringify(b.policies.production.baselines)) reasons.add('baselines');
    if (!reasons.size) reasons.add('other');
    rows.push({
      pr: prLabel(a),
      reasons: [...reasons].sort(),
      before: { salience: a.policies.production.salience, kinds: qa.map((q) => q.kind) },
      after: { salience: b.policies.production.salience, kinds: qb.map((q) => q.kind) },
    });
  }
  const tally = {};
  for (const r of rows) for (const x of r.reasons) tally[x] = (tally[x] ?? 0) + 1;
  const intervalOnly = rows.filter((r) => r.reasons.length === 1 && r.reasons[0] === 'interval').length;
  return { prsCompared: stage0b.prs.length, prsDiffering: rows.length, byReason: tally, intervalOnly, maxIntervalDelta: Number(maxIntervalDelta.toFixed(6)), rows };
}

export function buildResults({ defaultModel, legacyModel, stage0bModel, gu29Results, gate }) {
  return {
    schemaVersion: 1,
    kind: 'gutter-gu05-results',
    repo: defaultModel.repo.name,
    headSha: defaultModel.repo.headSha,
    gutterVersion: defaultModel.tools.gutter,
    raVersion: defaultModel.tools.repoArchaeology,
    gu29: { default: gu29Results.default, gate: gu29Results.gate },
    default: runShape(defaultModel),
    gate: gateSummary(gate),
    legacy: {
      shape: runShape(legacyModel),
      stage0b: summarizeRun('stage0b-default', stage0bModel),
      summary: summarizeRun('gu05-legacy', legacyModel),
      deltas: classifyDeltas(stage0bModel, legacyModel),
    },
  };
}

const f2 = (x) => (x === null || x === undefined ? 'N/A' : x.toFixed(2));
const prop = (m) => (m && m.denominator ? `${f2(m.rate)} [${f2(m.interval.low)}–${f2(m.interval.high)}] (${m.numerator}/${m.denominator})` : 'N/A');
const lift = (x) => (x === null || x === undefined ? 'N/A' : `×${f2(x)}`);
const ratio = (x) => `${x.confirmed}/${x.checked}`;
const yes = (met) => (met === null ? 'not exercised' : met ? '**MET**' : '**NOT MET**');
const REASON_TEXT = {
  dependents: 'Repo Archaeology\'s resolver found other importers, so a `wide-surface` or `broken-import` item appeared or went away',
  interval: 'a companion question\'s interval comes from Repo Archaeology (raw counts, rounded outward to 4 decimals) instead of Gutter\'s own Wilson computation',
  questions: 'another checklist item moved (an item crossed a gate, or the 4-item cap admitted or dropped one)',
  salience: 'the page\'s salience level changed as a consequence',
  outcomes: 'the same questions were scored with different targets or outcomes',
  baselines: 'the matched baselines changed because the number of scorable targets changed',
  other: 'another field of the record changed',
};

export function renderGu05(r) {
  const g29 = r.gu29.default;
  const d = r.default;
  const out = [MARK_GU05_START, ''];
  out.push(
    `Runs: \`${r.repo}\` at \`${r.headSha.slice(0, 7)}\`, gutter ${r.gutterVersion}, repo-archaeology ${r.raVersion}, ${d.prsEvaluated} PRs evaluated, production policy. ` +
      '"GU-29" is the committed GU-29 default run (interim relative-import scanner); "GU-05" builds dependents from Repo Archaeology\'s import graph in the same session as `diff` and `backtest`. Intervals are Wilson 95%.',
  );
  out.push('', '### R.1 Loudness and facts, GU-29 vs GU-05 (default config)', '');
  out.push('| Measure | GU-29 | GU-05 |', '|---|---|---|');
  out.push(`| Quiet share | ${prop(g29.salience.quiet)} | ${prop(d.salience.quiet)} |`);
  out.push(`| Brief share | ${prop(g29.salience.brief)} | ${prop(d.salience.brief)} |`);
  out.push(`| Full share (budget < 1/3) | ${prop(g29.salience.full)} | ${prop(d.salience.full)} |`);
  out.push(`| Checklist items per PR | ${f2(g29.checklistItemsPerPr)} (${g29.checklistItems}) | ${f2(d.checklistItemsPerPr)} (${d.checklistItems}) |`);
  for (const k of ['broken-import', 'wide-surface', 'untested-change']) {
    out.push(`| \`${k}\` items (PRs) | ${g29.byKind[k]} (${g29.prsWithKind[k]}) | ${d.byKind[k]} (${d.prsWithKind[k]}) |`);
  }
  const g = r.gate;
  const old = r.gu29.gate;
  out.push('', '### R.2 Gate A′, GU-29 vs GU-05', '');
  out.push(`Replay parity of the GU-05 check with its bench run: ${g.replayParity.salienceMismatches} salience and ${g.replayParity.checklistKindMismatches} checklist mismatches. Broken imports are re-confirmed with TypeScript ${g.tools.typescript}'s \`ts.resolveModuleName\`.`);
  out.push('', '| Criterion | Needs | GU-29 | GU-05 |', '|---|---|---|---|');
  out.push(`| (a) Full share | ≤ 1/3 | ${f2(old.a.share)} (${old.a.full}/${old.a.evaluated}) · ${yes(old.a.met)} | ${f2(g.a.share)} (${g.a.full}/${g.a.evaluated}) · ${yes(g.a.met)} |`);
  out.push(`| (b) \`broken-import\` confirmed | ≥ 95% | ${ratio(old.b.brokenImport)} · ${yes(old.b.brokenImport.met)} | ${ratio(g.b.brokenImport)} · ${yes(g.b.brokenImport.met)} |`);
  out.push(`| (b) \`untested-change\` facts | 100% | ${ratio(old.b.untestedChange)} · ${yes(old.b.untestedChange.met)} | ${ratio(g.b.untestedChange)} · ${yes(g.b.untestedChange.met)} |`);
  out.push(`| (b) Test-history facts | 100% | ${ratio(old.b.testHistory)} · ${yes(old.b.testHistory.met)} | ${ratio(g.b.testHistory)} · ${yes(g.b.testHistory.met)} |`);
  out.push(`| (c) Prediction wording | 0 hits | ${old.c.ownWordingHits} | ${g.c.ownWordingHits} |`);
  const v = evaluateGate(g);
  out.push('', `- **Gate A′ for hono (GU-05): ${v.verdict}.**${v.unexercised.length ? ` Not exercised on hono: ${v.unexercised.join(', ')}.` : ''}`);
  const L = r.legacy;
  out.push('', '### R.3 The research switch against Stage 0b', '');
  if (L.deltas.prsDiffering === 0) {
    out.push(`\`legacyPredictions: true\` still reproduces Stage 0b's default run: ${L.deltas.prsCompared} of ${L.deltas.prsCompared} PR records identical.`);
  } else {
    out.push(
      `\`legacyPredictions: true\` no longer reproduces Stage 0b record for record: ${L.deltas.prsDiffering} of ${L.deltas.prsCompared} PR records differ. ` +
        'Every difference is classified below; no Stage 0 or 0b verdict depends on it (both were decided on the Stage 0b data, which stays committed).',
    );
    out.push('', '| Measure | Stage 0b default | GU-05 legacy |', '|---|---|---|');
    out.push(`| Full-salience share | ${prop(L.stage0b.fullSalienceShare)} | ${prop(L.summary.fullSalienceShare)} |`);
    out.push(`| PRs scored / questions | ${L.stage0b.prsScored} / ${L.stage0b.questionsTotal} | ${L.summary.prsScored} / ${L.summary.questionsTotal} |`);
    for (const [id, label] of [['followUp', 'Any follow-up'], ['sameAuthor', 'Same-author follow-up'], ['raSignal', 'RA-signal follow-up']]) {
      out.push(`| ${label}: Gutter | ${prop(L.stage0b.gutter[id])} | ${prop(L.summary.gutter[id])} |`);
      out.push(`| ${label}: lift vs strongest | ${lift(L.stage0b.byOutcome?.[id]?.lift)} | ${lift(L.summary.byOutcome?.[id]?.lift)} |`);
    }
    out.push('', '| Why a record differs | PRs |', '|---|---:|');
    for (const [k, n] of Object.entries(L.deltas.byReason).sort()) out.push(`| ${REASON_TEXT[k] ?? k} | ${n} |`);
    out.push(
      '',
      `${L.deltas.intervalOnly} records differ only in a companion question's interval low bound (largest change ${L.deltas.maxIntervalDelta.toFixed(4)}); ` +
        'no question crossed the 0.3 floor, so no checklist changed for that reason. The other records:',
    );
    out.push('', '| PR | Reasons | Stage 0b: salience · items | GU-05 legacy: salience · items |', '|---|---|---|---|');
    for (const row of L.deltas.rows.filter((x) => !(x.reasons.length === 1 && x.reasons[0] === 'interval'))) {
      out.push(`| ${row.pr} | ${row.reasons.join(', ')} | ${row.before.salience} · ${row.before.kinds.join(', ') || '—'} | ${row.after.salience} · ${row.after.kinds.join(', ') || '—'} |`);
    }
  }
  out.push('', MARK_GU05_END);
  return out.join('\n');
}

function main() {
  const { values } = parseArgs({
    options: {
      default: { type: 'string' },
      legacy: { type: 'string' },
      stage0b: { type: 'string' },
      gu29: { type: 'string' },
      gate: { type: 'string' },
      'write-results': { type: 'string' },
      results: { type: 'string' },
      update: { type: 'string' },
    },
    strict: true,
  });
  const load = (f) => JSON.parse(readFileSync(f, 'utf8'));
  let results;
  if (values.default && values.legacy && values.stage0b && values.gu29 && values.gate) {
    results = buildResults({
      defaultModel: load(values.default),
      legacyModel: load(values.legacy),
      stage0bModel: load(values.stage0b),
      gu29Results: load(values.gu29),
      gate: load(values.gate),
    });
    if (values['write-results']) writeFileSync(values['write-results'], JSON.stringify(results, null, 2) + '\n');
  } else if (values.results) {
    results = load(values.results);
  } else {
    process.stderr.write('usage: gu05-report.mjs (--default --legacy --stage0b --gu29 --gate [--write-results <file>] | --results <file>) [--update STAGE0.md]\n');
    return 2;
  }
  const block = renderGu05(results);
  if (values.update) {
    writeFileSync(values.update, replaceGeneratedBlock(readFileSync(values.update, 'utf8'), block, MARK_GU05_START, MARK_GU05_END));
    process.stderr.write(`updated ${values.update}\n`);
  } else {
    process.stdout.write(block + '\n');
  }
  process.stderr.write(`gu05: Gate A′ ${evaluateGate(results.gate).verdict}; legacy records differing from Stage 0b: ${results.legacy.deltas.prsDiffering}\n`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('gu05-report.mjs')) {
  process.exitCode = main();
}
