/**
 * Per-PR comparison of two default runs of the same repository and settings (RA 0.4.0 vs 0.10.x),
 * ignoring fields that only exist in the newer run (`trackRecord`).
 */
export function analyzerDelta(oldModel, newModel) {
  const norm = (pr, keepCalibration) => {
    const c = structuredClone(pr);
    for (const pol of ['production', 'ungated']) {
      if (!keepCalibration) delete c.policies[pol].calibrationPrecision;
      for (const q of c.policies[pol].questions) delete q.trackRecord;
    }
    return JSON.stringify(c);
  };
  const byId = new Map(newModel.prs.map((p) => [p.id, p]));
  let compared = 0;
  let calibrationChanged = 0;
  let calibrationStatusChanged = 0;
  const questionsChanged = [];
  let minDelta = null;
  let maxDelta = null;
  for (const p of oldModel.prs) {
    const q = byId.get(p.id);
    if (!q) continue;
    compared++;
    const a = p.policies.production;
    const b = q.policies.production;
    if (a.calibrationStatus !== b.calibrationStatus) calibrationStatusChanged++;
    if (a.calibrationPrecision !== b.calibrationPrecision) {
      calibrationChanged++;
      const d = (b.calibrationPrecision ?? 0) - (a.calibrationPrecision ?? 0);
      minDelta = minDelta === null ? d : Math.min(minDelta, d);
      maxDelta = maxDelta === null ? d : Math.max(maxDelta, d);
    }
    if (norm(p, false) !== norm(q, false)) questionsChanged.push(p.prNumber !== null ? `#${p.prNumber}` : p.id);
  }
  return {
    fromRa: oldModel.tools.repoArchaeology,
    toRa: newModel.tools.repoArchaeology,
    prsCompared: compared,
    prsMissing: oldModel.prs.length - compared,
    prsWithOtherChanges: questionsChanged.length,
    prsWithOtherChangesList: questionsChanged.slice(0, 10),
    calibrationPrecisionChanged: calibrationChanged,
    calibrationStatusChanged,
    calibrationDelta: minDelta === null ? null : { min: Number(minDelta.toFixed(4)), max: Number(maxDelta.toFixed(4)) },
  };
}

export function evaluateStage0b(results) {
  const v4 = results.runs.find((r) => r.id === 'v4-proven-pairs');
  const sa = v4.byOutcome.sameAuthor;
  const ra = v4.byOutcome.raSignal;
  const liftPass = (sa.lift !== null && sa.lift > 1) || (ra.lift !== null && ra.lift > 1);
  const enough = v4.companionScoredTargets >= MIN_COMPANION_TARGETS_0B;
  const verdict = !enough ? 'INSUFFICIENT' : liftPass ? 'PASS' : 'FAIL';
  return { verdict, liftPass, enough, companionScoredTargets: v4.companionScoredTargets, sameAuthor: sa, raSignal: ra };
}

function outcomeTable(run, lines) {
  lines.push('| Outcome | Gutter | `popular` | `popular-near` | `recent` | Strongest | Lift vs strongest | Bootstrap CI |');
  lines.push('|---|---|---|---|---|---|---:|---|');
  for (const o of OUTCOMES) {
    const hl = run.byOutcome[o.id];
    const cells = BASELINES.map((b) => prop(run.baselines[b][o.id])).join(' | ');
    lines.push(
      `| ${o.label} | ${prop(run.gutter[o.id])} | ${cells} | \`${hl.strongestBaseline ?? 'N/A'}\` | ${lift(hl.lift)} | ${boot(hl.bootstrapCi)} |`,
    );
  }
}

const share = (m) => (m && m.denominator ? `${f2(m.numerator / m.denominator)} (${m.numerator}/${m.denominator})` : 'N/A');

export function renderStage0b(results, stage0Results) {
  const lines = [];
  const def = results.runs.find((r) => r.id === 'default');
  const v4 = results.runs.find((r) => r.id === 'v4-proven-pairs');
  const old = stage0Results?.runs.find((r) => r.id === 'default');
  const verdict = evaluateStage0b(results);
  const delta = results.analyzerDelta;
  lines.push(MARK0B_START);
  lines.push('');
  lines.push(
    `Runs: \`${def.repo}\` at \`${def.headSha.slice(0, 7)}\`, gutter ${def.gutterVersion}, repo-archaeology ${def.raVersion}, ` +
      `${def.prsEvaluated} PRs evaluated, production policy. Same intervals as Stage 0.`,
  );
  lines.push('');
  lines.push(`### 0b.R1 Analyzer delta: default run, repo-archaeology ${old?.raVersion ?? '?'} → ${def.raVersion}`);
  lines.push('');
  if (old) {
    lines.push(`| Measure | ${old.raVersion} (Stage 0) | ${def.raVersion} (Stage 0b) |`);
    lines.push('|---|---|---|');
    lines.push(`| Full-salience share | ${prop(old.fullSalienceShare)} | ${prop(def.fullSalienceShare)} |`);
    lines.push(`| PRs scored / questions | ${old.prsScored} / ${old.questionsTotal} | ${def.prsScored} / ${def.questionsTotal} |`);
    for (const o of OUTCOMES) {
      lines.push(`| ${o.label}: Gutter | ${prop(old.gutter[o.id])} | ${prop(def.gutter[o.id])} |`);
      lines.push(
        `| ${o.label}: lift vs strongest | ${lift(old.byOutcome[o.id].lift)} ${boot(old.byOutcome[o.id].bootstrapCi)} | ${lift(def.byOutcome[o.id].lift)} ${boot(def.byOutcome[o.id].bootstrapCi)} |`,
      );
    }
    lines.push('');
  }
  if (delta) {
    const cal = delta.calibrationDelta ? ` (by ${delta.calibrationDelta.min >= 0 ? '+' : ''}${delta.calibrationDelta.min} to ${delta.calibrationDelta.max >= 0 ? '+' : ''}${delta.calibrationDelta.max})` : '';
    lines.push(
      `Per PR (${delta.prsCompared} compared): calibration precision changed on ${delta.calibrationPrecisionChanged}${cal}, calibration status on ${delta.calibrationStatusChanged}; ` +
        `questions, outcomes, salience or baselines changed on ${delta.prsWithOtherChanges}` +
        (delta.prsWithOtherChanges ? ` (${delta.prsWithOtherChangesList.join(', ')})` : '') +
        '. The `trackRecord` field itself is ignored in this comparison.',
    );
    lines.push('');
  }
  lines.push('### 0b.R2 V4 · proven pairs, stricter outcomes');
  lines.push('');
  outcomeTable(v4, lines);
  lines.push('');
  lines.push('| Measure | Default | V4 · proven pairs |');
  lines.push('|---|---|---|');
  lines.push(`| PRs with a companion question (coverage) | ${share(def.companionCoverage)} | ${share(v4.companionCoverage)} |`);
  lines.push(`| Companion questions | ${def.companionQuestions} | ${v4.companionQuestions} |`);
  lines.push(`| Scored companion targets (needs ≥ ${MIN_COMPANION_TARGETS_0B}) | ${def.companionScoredTargets} | ${v4.companionScoredTargets} |`);
  lines.push(`| Companion follow-up (not decisive) | ${prop(def.companionFollowUp)} | ${prop(v4.companionFollowUp)} |`);
  lines.push(`| Companion same-author (not decisive) | ${prop(def.companionSameAuthor)} | ${prop(v4.companionSameAuthor)} |`);
  const ok = (r) => (r.fullSalienceShare.denominator && r.fullSalienceShare.numerator / r.fullSalienceShare.denominator < FULL_SHARE_BUDGET ? '✓' : '✗');
  lines.push(`| Full-salience share (budget < 1/3) | ${prop(def.fullSalienceShare)} ${ok(def)} | ${prop(v4.fullSalienceShare)} ${ok(v4)} |`);
  lines.push(`| PRs scored / questions (all kinds) | ${def.prsScored} / ${def.questionsTotal} | ${v4.prsScored} / ${v4.questionsTotal} |`);
  lines.push('');
  lines.push('### 0b.R3 Pass rule (preregistered in 0b.2)');
  lines.push('');
  lines.push(
    `- **Sample:** ${verdict.companionScoredTargets} scored \`forgotten-companion\` targets; needs ≥ ${MIN_COMPANION_TARGETS_0B}. **${verdict.enough ? 'MET' : 'NOT MET'}.**`,
  );
  lines.push(
    `- **Lift:** same-author ${lift(verdict.sameAuthor.lift)} vs \`${verdict.sameAuthor.strongestBaseline}\`, RA-signal ${lift(verdict.raSignal.lift)} vs \`${verdict.raSignal.strongestBaseline}\`; needs either > ×1.00. **${verdict.liftPass ? 'MET' : 'NOT MET'}.**` +
      (verdict.enough ? '' : ' (Not decisive: the sample condition failed, and with no companion targets this lift comes from the other question kinds.)'),
  );
  const text = {
    PASS: 'PASS: option 2 meets the preregistered rule on hono. A V4 label set is the next step before any decision.',
    FAIL: 'FAIL: option 2 does not beat the strongest baseline on hono.',
    INSUFFICIENT: `INSUFFICIENT: too few scored companion targets under V4 to judge option 2 on hono (${verdict.companionScoredTargets} < ${MIN_COMPANION_TARGETS_0B}).`,
  }[verdict.verdict];
  lines.push(`- **Option 2 verdict: ${text}**`);
  lines.push('');
  lines.push(MARK0B_END);
  return lines.join('\n');
}

function main() {
  const { values } = parseArgs({
    options: {
      runs: { type: 'string' },
      results: { type: 'string' },
      'write-results': { type: 'string' },
      labels: { type: 'string', multiple: true },
      update: { type: 'string' },
      stage0b: { type: 'boolean', default: false },
      'compare-bench': { type: 'string' },
      'stage0-results': { type: 'string' },
    },
    strict: true,
  });
  if (values.stage0b) return main0b(values);
  let results;
  if (values.runs) {
    results = buildResults(values.runs);
    if (values['write-results']) writeFileSync(values['write-results'], JSON.stringify(results, null, 2) + '\n');
  } else if (values.results) {
    results = JSON.parse(readFileSync(values.results, 'utf8'));
  } else {
    process.stderr.write('usage: stage0-report.mjs (--runs <dir> [--write-results <file>] | --results <file>) [--labels <file>...] [--update STAGE0.md]\n');
    return 2;
  }
  const def = results.runs.find((r) => r.id === 'default');
  const labelDocs = (values.labels ?? []).map((f) => JSON.parse(readFileSync(f, 'utf8')));
  const labelSummary = labelDocs.length ? summarizeLabels(labelDocs, def) : null;
  const block = renderResults(results, labelSummary);
  if (values.update) {
    writeFileSync(values.update, replaceGeneratedBlock(readFileSync(values.update, 'utf8'), block));
    process.stderr.write(`updated ${values.update}\n`);
  } else {
    process.stdout.write(block + '\n');
  }
  process.stderr.write(`stage0: ${evaluateDecision(results, labelSummary).verdict}\n`);
  return 0;
}

function main0b(values) {
  let results;
  if (values.runs) {
    results = { schemaVersion: 1, kind: 'gutter-stage0b-results', ...buildResults(values.runs, VARIANTS_0B) };
    results.kind = 'gutter-stage0b-results';
    if (values['compare-bench']) {
      const oldModel = JSON.parse(readFileSync(values['compare-bench'], 'utf8'));
      const newModel = JSON.parse(readFileSync(join(values.runs, 'default', 'bench.json'), 'utf8'));
      results.analyzerDelta = analyzerDelta(oldModel, newModel);
    }
    if (values['write-results']) writeFileSync(values['write-results'], JSON.stringify(results, null, 2) + '\n');
  } else if (values.results) {
    results = JSON.parse(readFileSync(values.results, 'utf8'));
  } else {
    process.stderr.write(
      'usage: stage0-report.mjs --stage0b (--runs <dir> [--compare-bench <stage0 default bench.json>] [--write-results <file>] | --results <file>) [--stage0-results <file>] [--update STAGE0.md]\n',
    );
    return 2;
  }
  const stage0Results = values['stage0-results'] ? JSON.parse(readFileSync(values['stage0-results'], 'utf8')) : null;
  const block = renderStage0b(results, stage0Results);
  if (values.update) {
    writeFileSync(values.update, replaceGeneratedBlock(readFileSync(values.update, 'utf8'), block, MARK0B_START, MARK0B_END));
    process.stderr.write(`updated ${values.update}\n`);
  } else {
    process.stdout.write(block + '\n');
  }
  process.stderr.write(`stage0b: ${evaluateStage0b(results).verdict}\n`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('stage0-report.mjs')) {
  process.exitCode = main();
}
