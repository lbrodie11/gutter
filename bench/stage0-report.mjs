#!/usr/bin/env node
// GU-04 Stage 0 report: turns the hono runs (and, once they exist, blinded labels) into the
// Results section of docs/benchmark/STAGE0.md and evaluates the preregistered decision rule.
//
// Zero dependencies; plain Node >= 22. Deterministic: same inputs, same output.
//
//   # 1. Summarize runs: <runs>/<variant>/bench.json -> results.json (aggregates only)
//   node bench/stage0-report.mjs --runs <dir> --write-results docs/benchmark/data/honojs__hono/stage0/results.json
//   # 2. Render (and optionally fold in labels), replacing the generated block in STAGE0.md
//   node bench/stage0-report.mjs --results docs/benchmark/data/honojs__hono/stage0/results.json \
//     [--labels labels.json ...] [--update docs/benchmark/STAGE0.md]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';

export const VARIANTS = [
  { id: 'default', label: 'Default (production)', config: null },
  { id: 'v1-floor', label: 'V1 · stricter floor', config: 'bench/variants/stage0-v1-floor.json' },
  { id: 'v2-two-signals', label: 'V2 · two signals', config: 'bench/variants/stage0-v2-two-signals.json' },
  { id: 'v3-breadth-not-full', label: 'V3 · breadth never full alone', config: 'bench/variants/stage0-v3-breadth-not-full.json' },
];
const BASELINES = ['popular', 'popular-near', 'recent'];
const OUTCOMES = [
  { id: 'followUp', label: 'Any follow-up' },
  { id: 'sameAuthor', label: 'Same-author follow-up' },
  { id: 'raSignal', label: 'RA-signal follow-up' },
];
const SOURCES = ['gutter', 'recent', 'popular-near'];
const LABEL_VALUES = ['useful', 'irrelevant', 'wrong'];
export const MARK_START = '<!-- stage0:results:start (generated by bench/stage0-report.mjs; do not edit by hand) -->';
export const MARK_END = '<!-- stage0:results:end -->';
const FULL_SHARE_BUDGET = 1 / 3;
const USEFUL_MARGIN = 0.15;

/** 95% Wilson score interval, identical to src/stats/wilson.ts. */
export function wilson(k, n, z = 1.959963984540054) {
  if (n <= 0) return null;
  const p = Math.min(Math.max(k / n, 0), 1);
  const z2 = z * z;
  const denom = 1 + z2 / n;
  const centre = p + z2 / (2 * n);
  const margin = z * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n));
  return { low: Math.max(0, (centre - margin) / denom), high: Math.min(1, (centre + margin) / denom) };
}

const f2 = (x) => (x === null || x === undefined ? 'N/A' : x.toFixed(2));
function prop(m) {
  if (!m || m.denominator === 0 || m.rate === null) return 'N/A';
  return `${f2(m.rate)} [${f2(m.interval.low)}–${f2(m.interval.high)}] (${m.numerator}/${m.denominator})`;
}
const bound = (x) => (x === null || x === undefined ? '∞' : x.toFixed(2));
/** Lift bootstrap: a null bound is unbounded (zero-hit baseline resamples reached that quantile). */
const boot = (b) => (b ? `[${bound(b.low)}–${bound(b.high)}]` : 'N/A');
const lift = (x) => (x === null || x === undefined ? 'N/A' : `×${f2(x)}`);

function outcomeMetric(source, outcome) {
  if (outcome === 'followUp') return source.fileLevelFollowUpPrecision ?? source.fileLevelFollowUp;
  if (outcome === 'sameAuthor') return source.sameAuthorFollowUpRate;
  return source.raSignalFollowUpRate;
}

/** Keep only what the report needs (the variants' ~1.5 MB bench.json files are not committed; the default run's is). */
export function summarizeRun(id, model) {
  const a = model.aggregates.production;
  if (!a.headlineBaseline.byOutcome) {
    throw new Error(`${id}: bench.json predates GU-04 Stage 0 metrics (no headlineBaseline.byOutcome); rerun gutter bench`);
  }
  return {
    id,
    repo: model.repo.name,
    headSha: model.repo.headSha,
    settingsHash: model.runIdentity.settingsHash,
    configOverrides: model.settings.configOverrides,
    gutterVersion: model.tools.gutter,
    raVersion: model.tools.repoArchaeology,
    prsEvaluated: a.coverage.prsEvaluated,
    prsScored: a.coverage.prsScored,
    questionsTotal: a.coverage.questionsTotal,
    fullSalienceShare: a.coverage.fullSalienceShare,
    gutter: {
      followUp: a.accuracyProxy.fileLevelFollowUpPrecision,
      sameAuthor: a.accuracyProxy.sameAuthorFollowUpRate,
      raSignal: a.accuracyProxy.raSignalFollowUpRate,
    },
    baselines: Object.fromEntries(
      BASELINES.map((b) => [b, Object.fromEntries(OUTCOMES.map((o) => [o.id, outcomeMetric(a.baselines[b], o.id)]))]),
    ),
    byOutcome: a.headlineBaseline.byOutcome,
    totalWallMs: model.timings.totalWallMs,
  };
}

export function buildResults(runsDir) {
  const runs = [];
  for (const v of VARIANTS) {
    const file = join(runsDir, v.id, 'bench.json');
    if (!existsSync(file)) throw new Error(`missing ${file}`);
    runs.push(summarizeRun(v.id, JSON.parse(readFileSync(file, 'utf8'))));
  }
  return { schemaVersion: 1, kind: 'gutter-stage0-results', runs };
}

/**
 * Pool label files; rates per source, per labeler, and completeness against the sample size.
 *
 * - The decision counts each item's blind choice (`firstLabel`, made before the reveal), never
 *   a label changed after the source and outcome were shown.
 * - One vote per (labeler, item): re-exports and duplicate files collapse to the latest label.
 * - A file without a labeler name is its own labeler, so two anonymous halves never add up to "complete".
 */
export function summarizeLabels(docs, defaultRun) {
  const problems = [];
  const byKey = new Map();
  let total = null;
  let sampleId = null;
  docs.forEach((doc, fileIndex) => {
    if (doc?.kind !== 'gutter-labels' || doc.mode !== 'compare') {
      problems.push('a labels file is not a gutter label --compare export');
      return;
    }
    if (defaultRun && (doc.bench?.headSha !== defaultRun.headSha || doc.bench?.settingsHash !== defaultRun.settingsHash)) {
      problems.push(`labels for sample ${doc.sampleId} come from a different bench run than the default run`);
      return;
    }
    if (sampleId !== null && doc.sampleId !== sampleId) {
      problems.push(`labels for sample ${doc.sampleId} do not match sample ${sampleId}; ignored`);
      return;
    }
    sampleId = doc.sampleId;
    total = total ?? doc.total;
    for (const l of doc.labels ?? []) {
      const blind = LABEL_VALUES.includes(l.firstLabel) ? l.firstLabel : l.label;
      if (!SOURCES.includes(l.source) || !LABEL_VALUES.includes(blind) || typeof l.questionId !== 'string') continue;
      const labeler = l.labeler ? String(l.labeler) : `(unnamed, file ${fileIndex + 1})`;
      const key = `${labeler}\u0000${l.questionId}`;
      const prev = byKey.get(key);
      if (!prev || String(l.labeledAt ?? '') >= String(prev.labeledAt ?? '')) {
        byKey.set(key, { ...l, labeler, blind });
      }
    }
  });
  const labels = [...byKey.values()];
  const labelers = [...new Set(labels.map((l) => l.labeler))].sort();
  const bySource = {};
  for (const s of SOURCES) {
    const ls = labels.filter((l) => l.source === s);
    const useful = ls.filter((l) => l.blind === 'useful').length;
    bySource[s] = {
      labeled: ls.length,
      useful,
      irrelevant: ls.filter((l) => l.blind === 'irrelevant').length,
      wrong: ls.filter((l) => l.blind === 'wrong').length,
      rate: ls.length ? useful / ls.length : null,
      interval: wilson(useful, ls.length),
    };
  }
  const perLabeler = labelers.map((name) => ({ name, count: labels.filter((l) => l.labeler === name).length }));
  const complete = total !== null && perLabeler.length > 0 && perLabeler.every((p) => p.count >= total);
  const changedAfterReveal = labels.filter((l) => l.changedAfterReveal).length;

  // Agreement on items labeled by exactly the first two labelers (raw percent agreement).
  let agreement = null;
  if (labelers.length >= 2) {
    const [a, b] = labelers;
    const byItem = (name) => new Map(labels.filter((l) => l.labeler === name).map((l) => [l.questionId, l.blind]));
    const ma = byItem(a);
    const mb = byItem(b);
    const shared = [...ma.keys()].filter((k) => mb.has(k));
    const same = shared.filter((k) => ma.get(k) === mb.get(k)).length;
    agreement = { labelers: [a, b], shared: shared.length, agree: same };
  }
  return { problems, total, labelers: perLabeler, complete, bySource, changedAfterReveal, agreement };
}

export function evaluateDecision(results, labelSummary) {
  const def = results.runs.find((r) => r.id === 'default');
  const sa = def.byOutcome.sameAuthor;
  const ra = def.byOutcome.raSignal;
  const liftPass = (sa.lift !== null && sa.lift > 1) || (ra.lift !== null && ra.lift > 1);
  let usefulPass = null;
  let better = null;
  if (labelSummary?.complete) {
    const r = labelSummary.bySource.recent.rate ?? 0;
    const p = labelSummary.bySource['popular-near'].rate ?? 0;
    better = p >= r ? 'popular-near' : 'recent';
    const g = labelSummary.bySource.gutter.rate ?? 0;
    usefulPass = g >= Math.max(r, p) + USEFUL_MARGIN - 1e-12;
  }
  let verdict;
  if (!liftPass) verdict = 'STOP';
  else if (usefulPass === null) verdict = 'INCOMPLETE';
  else verdict = usefulPass ? 'CONTINUE' : 'STOP';
  return { verdict, liftPass, usefulPass, better, sameAuthor: sa, raSignal: ra };
}

export function renderResults(results, labelSummary) {
  const lines = [];
  const def = results.runs.find((r) => r.id === 'default');
  const decision = evaluateDecision(results, labelSummary);
  lines.push(MARK_START);
  lines.push('');
  lines.push(
    `Runs: \`${def.repo}\` at \`${def.headSha.slice(0, 7)}\`, gutter ${def.gutterVersion}, repo-archaeology ${def.raVersion}, ` +
      `${def.prsEvaluated} PRs evaluated, production policy. Intervals are Wilson 95% for rates and PR-clustered bootstrap ` +
      '(seed 20261108, 1,000 resamples) for lifts.',
  );
  lines.push('');
  lines.push('### 1. Stricter outcomes, default policy');
  lines.push('');
  lines.push('| Outcome | Gutter | `popular` | `popular-near` | `recent` | Strongest | Lift vs strongest | Bootstrap CI |');
  lines.push('|---|---|---|---|---|---|---:|---|');
  for (const o of OUTCOMES) {
    const hl = def.byOutcome[o.id];
    const cells = BASELINES.map((b) => prop(def.baselines[b][o.id])).join(' | ');
    lines.push(
      `| ${o.label} | ${prop(def.gutter[o.id])} | ${cells} | \`${hl.strongestBaseline ?? 'N/A'}\` | ${lift(hl.lift)} | ${boot(hl.bootstrapCi)} |`,
    );
  }
  lines.push('');
  lines.push('### 2. Salience variants');
  lines.push('');
  lines.push(
    '| Variant | Config | Full share (budget < 1/3) | PRs scored | Questions | Follow-up | Same-author | RA-signal | Lift: follow-up | Lift: same-author | Lift: RA-signal |',
  );
  lines.push('|---|---|---|---:|---:|---|---|---|---:|---:|---:|');
  for (const v of VARIANTS) {
    const r = results.runs.find((x) => x.id === v.id);
    if (!r) continue;
    const share = r.fullSalienceShare;
    const ok = share.rate !== null && share.numerator / share.denominator < FULL_SHARE_BUDGET ? '✓' : '✗';
    const cfg = Object.keys(r.configOverrides).length ? `\`${JSON.stringify(r.configOverrides)}\`` : 'none';
    lines.push(
      `| ${v.label} | ${cfg} | ${prop(share)} ${ok} | ${r.prsScored} | ${r.questionsTotal} | ${prop(r.gutter.followUp)} | ${prop(r.gutter.sameAuthor)} | ${prop(r.gutter.raSignal)} | ` +
        `${lift(r.byOutcome.followUp.lift)} | ${lift(r.byOutcome.sameAuthor.lift)} | ${lift(r.byOutcome.raSignal.lift)} |`,
    );
  }
  lines.push('');
  lines.push('### 3. Blinded labels');
  lines.push('');
  for (const p of labelSummary?.problems ?? []) lines.push(`- ⚠ ${p}`);
  if (labelSummary?.problems?.length) lines.push('');
  if (!labelSummary || labelSummary.labelers.length === 0) {
    lines.push('No labels yet. Label the 60 items in [`label-compare.html`](data/honojs__hono/stage0/label-compare.html), export `labels.json`, and rerun this report.');
  } else {
    lines.push(
      `Labelers: ${labelSummary.labelers.map((l) => `${l.name} (${l.count}/${labelSummary.total})`).join(', ')}. ` +
        `Rates use each item's blind first label; ${labelSummary.changedAfterReveal} label(s) changed after the reveal, and those changes are ignored.`,
    );
    if (labelSummary.agreement) {
      const a = labelSummary.agreement;
      lines.push(`Agreement between ${a.labelers.join(' and ')}: ${a.agree}/${a.shared} shared items.`);
    }
    lines.push('');
    lines.push('| Source | Labeled | Useful | Irrelevant | Wrong | Useful rate [Wilson 95%] |');
    lines.push('|---|---:|---:|---:|---:|---|');
    for (const s of SOURCES) {
      const b = labelSummary.bySource[s];
      const rate = b.rate === null ? 'N/A' : `${f2(b.rate)} [${f2(b.interval.low)}–${f2(b.interval.high)}]`;
      lines.push(`| \`${s}\` | ${b.labeled} | ${b.useful} | ${b.irrelevant} | ${b.wrong} | ${rate} |`);
    }
  }
  lines.push('');
  lines.push('### 4. Decision rule (preregistered in section 4)');
  lines.push('');
  const sa = decision.sameAuthor;
  const ra = decision.raSignal;
  lines.push(
    `- **Lift condition:** same-author ${lift(sa.lift)} vs \`${sa.strongestBaseline}\`, RA-signal ${lift(ra.lift)} vs \`${ra.strongestBaseline}\`; ` +
      `needs either > ×1.00. **${decision.liftPass ? 'MET' : 'NOT MET'}.**`,
  );
  if (decision.usefulPass === null) {
    const have = labelSummary?.labelers?.length ? `${Math.min(...labelSummary.labelers.map((l) => l.count))} of ${labelSummary.total}` : `0 of 60`;
    lines.push(`- **Usefulness condition:** not evaluated, labels incomplete (${have}).`);
  } else {
    const g = labelSummary.bySource.gutter.rate;
    const b = labelSummary.bySource[decision.better].rate;
    lines.push(
      `- **Usefulness condition:** Gutter ${f2(g)} vs better baseline \`${decision.better}\` ${f2(b)} + 0.15 = ${f2(b + USEFUL_MARGIN)}. **${decision.usefulPass ? 'MET' : 'NOT MET'}.**`,
    );
  }
  const verdictText = {
    STOP: 'STOP: the preregistered rule says do not build the corpus. A human chooses among the options in section 5.',
    CONTINUE: 'CONTINUE: both conditions are met. A human confirms before the corpus is built.',
    INCOMPLETE: 'INCOMPLETE: the lift condition is met, but labels are missing.',
  }[decision.verdict];
  lines.push(`- **Rule outcome: ${verdictText}**`);
  lines.push('');
  lines.push(MARK_END);
  return lines.join('\n');
}

export function replaceGeneratedBlock(doc, block) {
  const start = doc.indexOf(MARK_START);
  const end = doc.indexOf(MARK_END);
  if (start === -1 || end === -1 || end < start) throw new Error('STAGE0.md has no generated results markers');
  return doc.slice(0, start) + block + doc.slice(end + MARK_END.length);
}

function main() {
  const { values } = parseArgs({
    options: {
      runs: { type: 'string' },
      results: { type: 'string' },
      'write-results': { type: 'string' },
      labels: { type: 'string', multiple: true },
      update: { type: 'string' },
    },
    strict: true,
  });
  let results;
  if (values.runs) {
    results = buildResults(values.runs);
    if (values['write-results']) writeFileSync(values['write-results'], JSON.stringify(results, null, 2) + '\n');
  } else if (values.results) {
    results = JSON.parse(readFileSync(values.results, 'utf8'));
  } else {
    process.stderr.write('usage: stage0-report.mjs (--runs <dir> [--write-results <file>] | --results <file>) [--labels <file>...] [--update STAGE0.md]\n');
    return 2;
  }
  const def = results.runs.find((r) => r.id === 'default');
  const labelDocs = (values.labels ?? []).map((f) => JSON.parse(readFileSync(f, 'utf8')));
  const labelSummary = labelDocs.length ? summarizeLabels(labelDocs, def) : null;
  const block = renderResults(results, labelSummary);
  if (values.update) {
    writeFileSync(values.update, replaceGeneratedBlock(readFileSync(values.update, 'utf8'), block));
    process.stderr.write(`updated ${values.update}\n`);
  } else {
    process.stdout.write(block + '\n');
  }
  process.stderr.write(`stage0: ${evaluateDecision(results, labelSummary).verdict}\n`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('stage0-report.mjs')) {
  process.exitCode = main();
}
