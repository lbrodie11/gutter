#!/usr/bin/env node
// GU-29 report: hono under the new defaults vs. the old ones, the research switch's reproduction of
// Stage 0b, and Gate A′. Writes results.json and the "After GU-29" block in STAGE0.md.
//
// Zero dependencies; plain Node >= 22. Deterministic: same inputs, same output.
//
//   # 1. Summarize: the two GU-29 runs, Stage 0b's default run, and the Gate A′ check -> results.json
//   node bench/gu29-report.mjs --default docs/benchmark/data/honojs__hono/gu29/default/bench.json \
//     --legacy docs/benchmark/data/honojs__hono/gu29/legacy/bench.json \
//     --before docs/benchmark/data/honojs__hono/stage0b/default/bench.json \
//     --gate docs/benchmark/data/honojs__hono/gu29/gate-a-prime.json \
//     --write-results docs/benchmark/data/honojs__hono/gu29/results.json
//   # 2. Render from results.json, replacing the generated block in STAGE0.md
//   node bench/gu29-report.mjs --results docs/benchmark/data/honojs__hono/gu29/results.json --update docs/benchmark/STAGE0.md
import { readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { replaceGeneratedBlock, summarizeRun, wilson } from './stage0-report.mjs';

export const MARK_GU29_START = '<!-- gu29:results:start (generated by bench/gu29-report.mjs; do not edit by hand) -->';
export const MARK_GU29_END = '<!-- gu29:results:end -->';
export const KINDS = ['broken-import', 'forgotten-companion', 'family-drift', 'untested-change', 'wide-surface'];
const FULL_SHARE_BUDGET = 1 / 3;

const share = (k, n) => ({ numerator: k, denominator: n, rate: n ? k / n : null, interval: wilson(k, n) });

/** Loudness and checklist shape of one run, production policy, from its PR records. */
export function runShape(model) {
  const prs = model.prs;
  const n = prs.length;
  const count = (level) => prs.filter((p) => p.policies.production.salience === level).length;
  const byKind = Object.fromEntries(KINDS.map((k) => [k, 0]));
  const prsWithKind = Object.fromEntries(KINDS.map((k) => [k, 0]));
  let items = 0;
  let prsWithItems = 0;
  for (const p of prs) {
    const qs = p.policies.production.questions;
    items += qs.length;
    if (qs.length) prsWithItems++;
    for (const k of KINDS) {
      const c = qs.filter((q) => q.kind === k).length;
      byKind[k] += c;
      if (c) prsWithKind[k]++;
    }
  }
  return {
    prsEvaluated: n,
    configOverrides: model.settings.configOverrides ?? {},
    salience: { quiet: share(count('quiet'), n), brief: share(count('brief'), n), full: share(count('full'), n) },
    checklistItems: items,
    checklistItemsPerPr: n ? Number((items / n).toFixed(4)) : null,
    prsWithItems: share(prsWithItems, n),
    byKind,
    prsWithKind,
  };
}

/** Where `untested-change` appears now but did not before, and how many of those the old `asked` set hid. */
export function untestedDelta(before, after) {
  const byId = new Map(before.prs.map((p) => [p.id, p]));
  const newlyShown = [];
  let hiddenByAsked = 0;
  for (const p of after.prs) {
    const item = p.policies.production.questions.find((q) => q.kind === 'untested-change');
    const old = byId.get(p.id)?.policies.production.questions ?? [];
    if (!item || old.some((q) => q.kind === 'untested-change')) continue;
    newlyShown.push(p.prNumber !== null ? `#${p.prNumber}` : p.id);
    const testFiles = new Set(item.targets.map((t) => t.targetFile));
    if (old.some((q) => q.kind === 'forgotten-companion' && q.targets.some((t) => testFiles.has(t.targetFile)))) hiddenByAsked++;
  }
  return { newlyShown: newlyShown.length, newlyShownList: newlyShown, hiddenByAskedBefore: hiddenByAsked };
}

/** The research switch must reproduce Stage 0b's default run: every PR record and every aggregate. */
export function reproduction(stage0b, legacy) {
  const byId = new Map(legacy.prs.map((p) => [p.id, p]));
  const differing = [];
  let compared = 0;
  for (const p of stage0b.prs) {
    const q = byId.get(p.id);
    if (!q) continue;
    compared++;
    if (JSON.stringify(p) !== JSON.stringify(q)) differing.push(p.prNumber !== null ? `#${p.prNumber}` : p.id);
  }
  const same = (k) => JSON.stringify(stage0b[k]) === JSON.stringify(legacy[k]);
  return {
    prsCompared: compared,
    prsMissing: stage0b.prs.length - compared,
    prsDiffering: differing.length,
    prsDifferingList: differing.slice(0, 10),
    aggregatesIdentical: same('aggregates'),
    gatesIdentical: same('gates'),
    funnelIdentical: same('funnel'),
    stage0b: summarizeRun('stage0b-default', stage0b),
    legacy: summarizeRun('gu29-legacy', legacy),
  };
}

export function gateSummary(gate) {
  const b = gate.b;
  const strip = (x) => ({ checked: x.checked, confirmed: x.confirmed, rate: x.rate, needs: x.needs, met: x.met, failures: x.failures.length });
  return {
    tools: gate.tools,
    prsEvaluated: gate.prsEvaluated,
    replayParity: gate.replayParity,
    a: gate.a,
    b: { brokenImport: strip(b.brokenImport), untestedChange: strip(b.untestedChange), testHistory: strip(b.testHistory) },
    c: { pagesChecked: gate.c.pagesChecked, ownWordingHits: gate.c.ownWordingHits.length, prTextHits: gate.c.prTextHits, met: gate.c.met },
  };
}

export function buildResults({ defaultModel, legacyModel, beforeModel, gate }) {
  return {
    schemaVersion: 1,
    kind: 'gutter-gu29-results',
    repo: defaultModel.repo.name,
    headSha: defaultModel.repo.headSha,
    gutterVersion: defaultModel.tools.gutter,
    raVersion: defaultModel.tools.repoArchaeology,
    before: runShape(beforeModel),
    default: runShape(defaultModel),
    legacy: runShape(legacyModel),
    untestedChange: untestedDelta(beforeModel, defaultModel),
    reproduction: reproduction(beforeModel, legacyModel),
    gate: gateSummary(gate),
  };
}

/** Gate A′ verdict. A criterion with no items on this repo is reported as not exercised, never as met. */
export function evaluateGate(g) {
  const parts = [g.a.met, g.b.untestedChange.met, g.b.testHistory.met, g.b.brokenImport.met, g.c.met];
  const failed = parts.some((p) => p === false);
  const unexercised = [];
  if (g.b.brokenImport.met === null) unexercised.push('broken-import (no items)');
  if (g.b.untestedChange.met === null) unexercised.push('untested-change (no items)');
  if (g.b.testHistory.met === null) unexercised.push('test history (no items)');
  if (failed) return { verdict: 'FAIL', unexercised };
  return { verdict: unexercised.length ? 'PASS (partly unexercised)' : 'PASS', unexercised };
}

const f2 = (x) => (x === null || x === undefined ? 'N/A' : x.toFixed(2));
const prop = (m) => (m.denominator ? `${f2(m.rate)} [${f2(m.interval.low)}–${f2(m.interval.high)}] (${m.numerator}/${m.denominator})` : 'N/A');
const ratio = (x) => `${x.confirmed}/${x.checked}`;
const yes = (met) => (met === null ? 'not exercised' : met ? '**MET**' : '**NOT MET**');
const lift = (x) => (x === null || x === undefined ? 'N/A' : `×${f2(x)}`);

export function renderGu29(r) {
  const b = r.before;
  const d = r.default;
  const out = [MARK_GU29_START, ''];
  out.push(
    `Runs: \`${r.repo}\` at \`${r.headSha.slice(0, 7)}\`, gutter ${r.gutterVersion}, repo-archaeology ${r.raVersion}, ${d.prsEvaluated} PRs evaluated, production policy. ` +
      '"Before" is Stage 0b\'s default run (the pre-GU-29 defaults on the same analyzer); "after" is the GU-29 default. Intervals are Wilson 95%.',
  );
  out.push('', '### G.1 Loudness and checklist, before and after', '');
  out.push('| Measure | Before GU-29 | After GU-29 |', '|---|---|---|');
  out.push(`| Quiet share | ${prop(b.salience.quiet)} | ${prop(d.salience.quiet)} |`);
  out.push(`| Brief share | ${prop(b.salience.brief)} | ${prop(d.salience.brief)} |`);
  out.push(`| Full share (budget < 1/3) | ${prop(b.salience.full)} ${b.salience.full.rate < FULL_SHARE_BUDGET ? '✓' : '✗'} | ${prop(d.salience.full)} ${d.salience.full.rate < FULL_SHARE_BUDGET ? '✓' : '✗'} |`);
  out.push(`| Checklist items per PR | ${f2(b.checklistItemsPerPr)} (${b.checklistItems}) | ${f2(d.checklistItemsPerPr)} (${d.checklistItems}) |`);
  out.push(`| PRs with at least one item | ${prop(b.prsWithItems)} | ${prop(d.prsWithItems)} |`);
  for (const k of KINDS) out.push(`| \`${k}\` items (PRs) | ${b.byKind[k]} (${b.prsWithKind[k]}) | ${d.byKind[k]} (${d.prsWithKind[k]}) |`);
  const u = r.untestedChange;
  out.push(
    '',
    `\`untested-change\` (now worded as a statement) appears on ${d.prsWithKind['untested-change']} PRs, up from ${b.prsWithKind['untested-change']}: ` +
      `${u.newlyShown} PRs show it for the first time, and ${u.hiddenByAskedBefore} of those had it hidden before because a companion question already asked about the same test file (the old \`asked\` set). ` +
      `Before GU-29, ${b.prsWithKind['forgotten-companion']} PRs carried a companion question and ${b.prsWithKind['family-drift']} a family-drift question; both are gone by default.`,
  );
  const rep = r.reproduction;
  out.push('', '### G.2 The research switch reproduces Stage 0b', '');
  out.push(
    `\`legacyPredictions: true\` ([\`bench/variants/gu29-legacy.json\`](../../bench/variants/gu29-legacy.json)) against Stage 0b's default run: ` +
      `${rep.prsCompared - rep.prsDiffering} of ${rep.prsCompared} PR records identical (${rep.prsMissing} missing); aggregates ${rep.aggregatesIdentical ? 'identical' : 'DIFFER'}, ` +
      `gates ${rep.gatesIdentical ? 'identical' : 'DIFFER'}, funnel ${rep.funnelIdentical ? 'identical' : 'DIFFER'}. Only the run identity (\`configOverrides\`, settings hash) and timestamps differ.`,
  );
  out.push('', '| Measure | Stage 0b default | GU-29 legacy |', '|---|---|---|');
  const s0 = rep.stage0b;
  const lg = rep.legacy;
  out.push(`| Full-salience share | ${prop(s0.fullSalienceShare)} | ${prop(lg.fullSalienceShare)} |`);
  out.push(`| PRs scored / questions | ${s0.prsScored} / ${s0.questionsTotal} | ${lg.prsScored} / ${lg.questionsTotal} |`);
  for (const [id, label] of [['followUp', 'Any follow-up'], ['sameAuthor', 'Same-author follow-up'], ['raSignal', 'RA-signal follow-up']]) {
    out.push(`| ${label}: Gutter | ${prop(s0.gutter[id])} | ${prop(lg.gutter[id])} |`);
    out.push(`| ${label}: lift vs strongest | ${lift(s0.byOutcome?.[id]?.lift)} | ${lift(lg.byOutcome?.[id]?.lift)} |`);
  }
  const g = r.gate;
  const verdict = evaluateGate(g);
  out.push('', '### G.3 Gate A′ on hono (docs/ROADMAP.md, M0 exit test)', '');
  out.push(
    `Checked by [\`bench/gate-a-prime.ts\`](../../bench/gate-a-prime.ts), which replays all ${g.prsEvaluated} PRs in default mode ` +
      `(replay parity with the bench run: ${g.replayParity.salienceMismatches} salience and ${g.replayParity.checklistKindMismatches} checklist mismatches) ` +
      `and re-checks every fact against git with TypeScript ${g.tools.typescript}.`,
  );
  out.push('', '| Criterion | Needs | hono | Result |', '|---|---|---|---|');
  out.push(`| (a) Quiet enough: full share | ≤ 1/3 | ${f2(g.a.share)} (${g.a.full}/${g.a.evaluated}) | ${yes(g.a.met)} |`);
  out.push(`| (b) \`broken-import\` confirmed by \`ts.resolveModuleName\` | ≥ 95% | ${ratio(g.b.brokenImport)} | ${yes(g.b.brokenImport.met)} |`);
  out.push(`| (b) \`untested-change\` facts match git | 100% | ${ratio(g.b.untestedChange)} | ${yes(g.b.untestedChange.met)} |`);
  out.push(`| (b) Test-history facts match git | 100% | ${ratio(g.b.testHistory)} | ${yes(g.b.testHistory.met)} |`);
  out.push(`| (c) No prediction wording on any page | 0 hits | ${g.c.ownWordingHits} hits on ${g.c.pagesChecked} replayed pages | ${yes(g.c.met)} |`);
  out.push('', `- **Gate A′ for hono: ${verdict.verdict}.**${verdict.unexercised.length ? ` Not exercised on hono: ${verdict.unexercised.join(', ')}; the corpus has to exercise it.` : ''}`);
  out.push('', MARK_GU29_END);
  return out.join('\n');
}

function main() {
  const { values } = parseArgs({
    options: {
      default: { type: 'string' },
      legacy: { type: 'string' },
      before: { type: 'string' },
      gate: { type: 'string' },
      'write-results': { type: 'string' },
      results: { type: 'string' },
      update: { type: 'string' },
    },
    strict: true,
  });
  const load = (f) => JSON.parse(readFileSync(f, 'utf8'));
  let results;
  if (values.default && values.legacy && values.before && values.gate) {
    results = buildResults({ defaultModel: load(values.default), legacyModel: load(values.legacy), beforeModel: load(values.before), gate: load(values.gate) });
    if (values['write-results']) writeFileSync(values['write-results'], JSON.stringify(results, null, 2) + '\n');
  } else if (values.results) {
    results = load(values.results);
  } else {
    process.stderr.write('usage: gu29-report.mjs (--default <bench.json> --legacy <bench.json> --before <bench.json> --gate <gate.json> [--write-results <file>] | --results <file>) [--update STAGE0.md]\n');
    return 2;
  }
  const block = renderGu29(results);
  if (values.update) {
    writeFileSync(values.update, replaceGeneratedBlock(readFileSync(values.update, 'utf8'), block, MARK_GU29_START, MARK_GU29_END));
    process.stderr.write(`updated ${values.update}\n`);
  } else {
    process.stdout.write(block + '\n');
  }
  process.stderr.write(`gu29: Gate A′ ${evaluateGate(results.gate).verdict}\n`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('gu29-report.mjs')) {
  process.exitCode = main();
}
